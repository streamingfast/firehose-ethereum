//! Diagnostic Substreams exercising the two RPC WASM extensions a `fireeth` instance registers,
//! `rpc::eth_call` and `rpc::eth_get_balance`.
//!
//! Each extension is enabled by its own `fireeth` flag, `--substreams-rpc-endpoints` and
//! `--substreams-rpc-get-balance-endpoints`, and an operator may well have configured only one
//! of them. They are therefore exercised by two separate modules so that a missing endpoint
//! fails the module that needs it instead of the whole package. `map_eth_methods` runs both for
//! the common case where everything is expected to work.

// The handler macro expands a module taking a `params` input into an `extern "C"` wrapper reading
// the string out of a raw pointer. Clippy reports that on the handler we wrote rather than on the
// generated wrapper, and the macro drops any attribute we would put on the handler to silence it.
#![allow(clippy::not_unsafe_ptr_arg_deref)]

mod abi;
mod params;

